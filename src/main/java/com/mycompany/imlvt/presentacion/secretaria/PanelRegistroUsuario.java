private void configurarReglaRolEspecialidad() {
    actualizarEstadoEspecialidad();

    cmbRol.addActionListener(e -> actualizarEstadoEspecialidad());
}

private void actualizarEstadoEspecialidad() {
    Object rolObj = cmbRol.getSelectedItem();
    String rol = (rolObj != null) ? rolObj.toString().trim() : "";

    boolean esMedico = rol.equalsIgnoreCase("Medico")
            || rol.equalsIgnoreCase("Médico")
            || rol.equalsIgnoreCase("Doctor");

    cmbEspecialidad.setEnabled(esMedico);
    if (!esMedico) {
        if (cmbEspecialidad.getItemCount() > 0) {
            cmbEspecialidad.setSelectedIndex(0);
        }
    }
}
private void limpiarCamposUsuario() {
    txtCedula.setText("");
    txtNombreyApellido.setText("");
    txtCorreo.setText("");
    txtContraseña.setText("");

    if (cmbRol.getItemCount() > 0) {
        cmbRol.setSelectedIndex(0);
    }
    actualizarEstadoEspecialidad();
    txtCedula.requestFocusInWindow();
}
