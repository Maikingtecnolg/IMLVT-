    private void buscarPacientePorCedula() {
        String cedula = txtCedula.getText().trim();

        if (cedula.isEmpty() || cedula.equalsIgnoreCase("ej 0801808829")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor ingrese un número de cédula.");
            txtCedula.requestFocus();
            return;
        }

        com.mycompany.imlvt.servicios.ServiciosSecretaria servicio = new com.mycompany.imlvt.servicios.ServiciosSecretaria();
        String nombrePaciente = servicio.buscarNombrePaciente(cedula);

        if (nombrePaciente != null && !nombrePaciente.trim().isEmpty()) {
            txtNombre.setText(nombrePaciente);
            cbxEspecialidad.requestFocus();
        } else {
            txtNombre.setText("");
            javax.swing.JOptionPane.showMessageDialog(this, 
                "El paciente con cédula " + cedula + " no se encuentra registrado.", 
                "Paciente no encontrado", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
            txtNombre.requestFocus();
        }
    
    }//GEN-LAST:event_txtCedulaActionPerformed

