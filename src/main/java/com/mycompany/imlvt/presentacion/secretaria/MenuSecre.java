    private void configurarEventos() {
        jButton1.addActionListener(e -> cargarTablaCitas());
        jComboBox1.addActionListener(e -> cargarTablaCitas());
        jComboBox2.addActionListener(e -> cargarTablaCitas());

        jTextField1.addKeyListener(new java.awt.event.KeyAdapter() {
            @Override
            public void keyReleased(java.awt.event.KeyEvent evt) {
                cargarTablaCitas();
            }
        });
    }

    private void cargarResumenTarjetas() {
        jLabel6.setText(String.valueOf(serviciosSecretaria.obtenerTotalCitasHoy()));
        jLabel7.setText(String.valueOf(serviciosSecretaria.obtenerTotalPendientesHoy()));
        jLabel8.setText(String.valueOf(serviciosSecretaria.obtenerTotalMedicosDisponibles()));
    }

    private void cargarTablaCitas() {
        String[] columnas = {"ID", "Cédula", "Paciente", "Fecha", "Hora", "Especialidad", "Estado"};
        DefaultTableModel modelo = new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        String tiempoSeleccionado = jComboBox1.getSelectedItem() != null
                ? jComboBox1.getSelectedItem().toString() : "Todas las citas";
        String estadoSeleccionado = jComboBox2.getSelectedItem() != null
                ? jComboBox2.getSelectedItem().toString() : "Todos";
        String textoBusqueda = jTextField1.getText();

        List<Object[]> filas = serviciosSecretaria.buscarCitasMenuSecre(
                tiempoSeleccionado, estadoSeleccionado, textoBusqueda
        );

        for (Object[] fila : filas) {
            modelo.addRow(fila);
        }

        jTable1.setModel(modelo);
    }
