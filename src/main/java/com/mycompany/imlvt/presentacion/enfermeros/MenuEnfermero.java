    private void bnt_buscarPacientesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bnt_buscarPacientesActionPerformed
        // TODO add your handling code here:
        // 1. Obtener el texto ingresado en la caja de cédula
        String cedulaBuscada = txtBuscarPaciente.getText().trim();

        if (cedulaBuscada.isEmpty() || cedulaBuscada.equals("Buscar Paciente")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor ingrese una cédula para buscar.");
            return;
        }

        try {
            java.sql.Connection con = com.mycompany.imlvt.datos.ConexionDB.obtenerConexion();

            String query = "SELECT u.cedula, u.nombres, c.hora, c.estado " +
                           "FROM usuarios u " +
                           "LEFT JOIN citas_medicas c ON u.cedula = c.cedula_paciente " +
                           "WHERE u.rol = 'Paciente' AND u.cedula = ?";

            java.sql.PreparedStatement ps = con.prepareStatement(query);
            ps.setString(1, cedulaBuscada);
            java.sql.ResultSet rs = ps.executeQuery();

            javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblPacientes.getModel();
            model.setRowCount(0);

            boolean encontrado = false;
            while (rs.next()) {
                encontrado = true;
                String nombre = rs.getString("nombres");
                String horaCita = rs.getString("hora");
                if (horaCita == null) horaCita = "Sin cita";

                String cedula = rs.getString("cedula");
                String estado = rs.getString("estado");
                if (estado == null) estado = "En espera";

                model.addRow(new Object[]{nombre, horaCita, cedula, estado});
            }

            if (!encontrado) {
                javax.swing.JOptionPane.showMessageDialog(this, "No se encontró ningún paciente registrado con esa cédula.");
            }

            rs.close();
            ps.close();
            con.close();

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al consultar la base de datos: " + e.getMessage());
        }
    }//GEN-LAST:event_bnt_buscarPacientesActionPerformed

