    private void btn_RecetaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_RecetaActionPerformed
        // TODO add your handling code here:
        String medicamento = txt_medicamento.getText().trim();
    String dosis = txt_dosis.getText().trim();
    String duracion = txt_duracion.getText().trim();
    String sintomas = txtSintomas.getText().trim();
    String diagnostico = txt_diagnostico.getText().trim();

    if (medicamento.isEmpty() || dosis.isEmpty()
            || duracion.isEmpty() || sintomas.isEmpty()
            || diagnostico.isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Completa todos los campos.");
        return;
    }

    DefaultTableModel modelo =
            (DefaultTableModel) Table_Medicamentos.getModel();
    for (int i = modelo.getRowCount() - 1; i >= 0; i--) {

        boolean vacia = true;

        for (int j = 0; j < modelo.getColumnCount(); j++) {
            Object valor = modelo.getValueAt(i, j);

            if (valor != null && !valor.toString().trim().isEmpty()) {
                vacia = false;
                break;
            }
        }

        if (vacia) {
            modelo.removeRow(i);
        }
    }

    modelo.addRow(new Object[]{
        medicamento, dosis, duracion, sintomas, diagnostico
    });

    txt_medicamento.setText("");
    txt_dosis.setText("");
    txt_duracion.setText("");
    txtSintomas.setText("");
    txt_diagnostico.setText("");
        
    }//GEN-LAST:event_btn_RecetaActionPerformed

    private void btn_eliminarRActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_eliminarRActionPerformed
        // TODO add your handling code here:
         int fila = Table_Medicamentos.getSelectedRow();

    if (fila == -1) {
        JOptionPane.showMessageDialog(this,
                "Seleccione un medicamento de la tabla.");
        return;
    }

    if (fila >= idsMedicamentos.size()) {

        int confirmarNuevo = JOptionPane.showConfirmDialog(this,
                "¿Desea quitar este medicamento de la tabla?",
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION);

        if (confirmarNuevo == JOptionPane.YES_OPTION) {

            DefaultTableModel modelo =
                    (DefaultTableModel) Table_Medicamentos.getModel();

            modelo.removeRow(fila);
        }

        return;
    }

    int id = idsMedicamentos.get(fila);

    int confirmar = JOptionPane.showConfirmDialog(this,
            "¿Está seguro de eliminar este medicamento?",
            "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION);

    if (confirmar == JOptionPane.YES_OPTION) {

        if (medicamentoDAO.eliminarMedicamento(id)) {

            cargarMedicamentos();

            JOptionPane.showMessageDialog(this,
                    "Medicamento eliminado correctamente.");

        } else {
            JOptionPane.showMessageDialog(this,
                    "No se pudo eliminar el medicamento.");
        }
    }
    }//GEN-LAST:event_btn_eliminarRActionPerformed

    private void btn_GuardarRActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_GuardarRActionPerformed
     
    String cedulaPaciente = (this.cedulaActual != null) ? this.cedulaActual.trim() : "";
    if (cedulaPaciente.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Seleccione un paciente antes de guardar la receta.",
                "Aviso",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    DefaultTableModel modelo = (DefaultTableModel) Table_Medicamentos.getModel();

    int guardados = 0;
    int errores = 0;

    for (int i = 0; i < modelo.getRowCount(); i++) {
        Object oMed = modelo.getValueAt(i, 0);
        Object oDos = modelo.getValueAt(i, 1);
        Object oDur = modelo.getValueAt(i, 2);
        Object oSin = modelo.getValueAt(i, 3);
        Object oDia = modelo.getValueAt(i, 4);

        String medicamento = oMed != null ? oMed.toString().trim() : "";
        String dosis = oDos != null ? oDos.toString().trim() : "";
        String duracion = oDur != null ? oDur.toString().trim() : "";
        String sintomas = oSin != null ? oSin.toString().trim() : "";
        String diagnostico = oDia != null ? oDia.toString().trim() : "";

        if (medicamento.isEmpty() || dosis.isEmpty()
                || duracion.isEmpty() || sintomas.isEmpty()
                || diagnostico.isEmpty()) {
            errores++;
            continue;
        }

        boolean resultado = medicamentoDAO.guardarMedicamentoConPaciente(
                cedulaPaciente, medicamento, dosis, duracion, sintomas, diagnostico
        );

        if (resultado) {
            guardados++;
        } else {
            errores++;
        }
    }

    cargarMedicamentos();

    JOptionPane.showMessageDialog(this,
            "Medicamentos guardados: " + guardados
            + "\nErrores: " + errores);

    }//GEN-LAST:event_btn_GuardarRActionPerformed
private final javax.swing.JPopupMenu popupPacientes = new javax.swing.JPopupMenu();
private final javax.swing.DefaultListModel<ItemPacienteCita> modeloPacientes = new javax.swing.DefaultListModel<>();
private final javax.swing.JList<ItemPacienteCita> listaPacientes = new javax.swing.JList<>(modeloPacientes);

private static class ItemPacienteCita {
   final int idCita;
    final String cedula;
    final String nombre;
    final String infoCita;

    ItemPacienteCita(String cedula, String nombre, String infoCita) {
        this(-1, cedula, nombre, infoCita);
    }

    ItemPacienteCita(int idCita, String cedula, String nombre, String infoCita) {
        this.idCita = idCita;
        this.cedula = cedula;
        this.nombre = nombre;
        this.infoCita = infoCita;
    }

    @Override
    public String toString() {
        return nombre + " (" + cedula + ") - " + infoCita;
    }
}

private void configurarBusquedaPacientes() {
    listaPacientes.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
    javax.swing.JScrollPane scroll = new javax.swing.JScrollPane(listaPacientes);
    scroll.setBorder(javax.swing.BorderFactory.createEmptyBorder());

    popupPacientes.setFocusable(false);
    popupPacientes.removeAll();
    popupPacientes.add(scroll);

    txtNombrePaciente.getDocument().addDocumentListener(new javax.swing.event.DocumentListener() {
        @Override
        public void insertUpdate(javax.swing.event.DocumentEvent e) {
            actualizarListitaPacientes();
        }

        @Override
        public void removeUpdate(javax.swing.event.DocumentEvent e) {
            actualizarListitaPacientes();
        }

        @Override
        public void changedUpdate(javax.swing.event.DocumentEvent e) {
            actualizarListitaPacientes();
        }
    });

    txt_buscarp.addActionListener(e -> actualizarListitaPacientes());

    listaPacientes.addMouseListener(new java.awt.event.MouseAdapter() {
        @Override
        public void mouseClicked(java.awt.event.MouseEvent evt) {
            if (evt.getClickCount() >= 1) {
                elegirPacienteDeLista();
            }
        }
    });

    txtNombrePaciente.addKeyListener(new java.awt.event.KeyAdapter() {
        @Override
        public void keyPressed(java.awt.event.KeyEvent evt) {
            if (!popupPacientes.isVisible()) return;
            int idx = listaPacientes.getSelectedIndex();
            int total = modeloPacientes.size();

            if (evt.getKeyCode() == java.awt.event.KeyEvent.VK_DOWN && idx < total - 1) {
                listaPacientes.setSelectedIndex(idx + 1);
                listaPacientes.ensureIndexIsVisible(idx + 1);
                evt.consume();
            } else if (evt.getKeyCode() == java.awt.event.KeyEvent.VK_UP && idx > 0) {
                listaPacientes.setSelectedIndex(idx - 1);
                listaPacientes.ensureIndexIsVisible(idx - 1);
                evt.consume();
            } else if (evt.getKeyCode() == java.awt.event.KeyEvent.VK_ENTER) {
                elegirPacienteDeLista();
                evt.consume();
            } else if (evt.getKeyCode() == java.awt.event.KeyEvent.VK_ESCAPE) {
                popupPacientes.setVisible(false);
            }
        }
    });
}

private void actualizarListitaPacientes() {
    String texto = txtNombrePaciente.getText().trim();
    modeloPacientes.clear();

    java.util.List<String[]> encontrados = medicoService.listarPacientesConCita(texto);

    for (String[] fila : encontrados) {
        String ced = fila.length > 0 && fila[0] != null ? fila[0] : "";
        String nom = fila.length > 1 && fila[1] != null ? fila[1] : "";
        String info = fila.length > 2 && fila[2] != null ? fila[2] : "";
        modeloPacientes.addElement(new ItemPacienteCita(ced, nom, info));
    }

    if (modeloPacientes.isEmpty()) {
        popupPacientes.setVisible(false);
        return;
    }

    listaPacientes.setSelectedIndex(0);
    int ancho = txtNombrePaciente.getWidth() > 0 ? txtNombrePaciente.getWidth() : 469;
    int alto = Math.min(modeloPacientes.size() * 26 + 6, 150);
    popupPacientes.setPopupSize(ancho, alto);
    popupPacientes.show(txtNombrePaciente, 0, txtNombrePaciente.getHeight());
}

private void elegirPacienteDeLista() {
   ItemPacienteCita elegido = listaPacientes.getSelectedValue();
    if (elegido == null) return;
    popupPacientes.setVisible(false);
    this.idCitaActual = elegido.idCita;
    this.cedulaActual = elegido.cedula;
    txtNombrePaciente.setText(elegido.nombre);
    llenarCamposConDatos(elegido.cedula);
    cargarMedicamentos();
}
