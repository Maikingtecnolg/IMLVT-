            String numeroTelefono = "593984517090"; 
         
         
            String mensaje = "Hola clínica IMLVT, soy " + " y necesito agendar una cita médica.";
            
            mensaje = mensaje.replace(" ", "%20");
            
            String url = "https://wa.me/" + numeroTelefono + "?text=" + mensaje;
            
