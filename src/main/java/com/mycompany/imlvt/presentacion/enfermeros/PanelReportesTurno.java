    private void btn_generarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_generarActionPerformed
        // TODO add your handling code here:
        String turno = cmbTurno.getSelectedItem() != null ? cmbTurno.getSelectedItem().toString().trim() : "";
        String enfermera = txtenfermera.getText().trim();
        java.util.Date fechaSeleccionada = dateFecha.getDate();
        int totalPacientes = Integer.parseInt(spnTotalPacientes.getValue().toString());
        String detalles = txtDetallesTurno.getText().trim();

        if (turno.isEmpty() || enfermera.isEmpty() || fechaSeleccionada == null || detalles.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Por favor complete el turno, enfermera/o, fecha y detalles de entrega.",
                "Campos incompletos",
                javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("yyyy-MM-dd");
        String fechaTexto = sdf.format(fechaSeleccionada);

        String reporte = "=== REPORTE DE ENTREGA DE TURNO ===\n"
                + "Turno: " + turno + "\n"
                + "Enfermera/o: " + enfermera + "\n"
                + "Fecha: " + fechaTexto + "\n"
                + "Total de Pacientes: " + totalPacientes + "\n\n"
                + "Detalles de Entrega de Turno:\n"
                + detalles;

        javax.swing.JOptionPane.showMessageDialog(
            this,
            reporte,
            "Reporte Generado",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
        );
    }//GEN-LAST:event_btn_generarActionPerformed


